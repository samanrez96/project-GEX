# API-level: multiple used items via POST
# ---------------------------------------------------------------------------

class SurgeryUsedItemAPIMultipleTest(APITestCase):

    def setUp(self):
        self.user = User.objects.create_user(username="si_api_user", password="x")
        self.client.force_authenticate(self.user)

        self.surgery_type = _surgery_type()
        self.patient      = _patient()
        self.surgery      = _surgery(self.patient, self.surgery_type)
        self.p1 = _product(stock=Decimal("100"))
        self.p2 = _product(stock=Decimal("200"))

    def test_two_api_posts_decrease_two_products(self):
        url = "/api/v2/surgeries/used-items/"
        resp1 = self.client.post(url, {
            "surgery": self.surgery.id,
            "product": self.p1.id,
            "quantity": "30",
        })
        resp2 = self.client.post(url, {
            "surgery": self.surgery.id,
            "product": self.p2.id,
            "quantity": "50",
        })
        self.assertEqual(resp1.status_code, 201)
        self.assertEqual(resp2.status_code, 201)

        self.p1.refresh_from_db()
        self.p2.refresh_from_db()
        self.assertEqual(self.p1.current_stock, Decimal("70"))
        self.assertEqual(self.p2.current_stock, Decimal("150"))

    def test_insufficient_stock_on_second_item_leaves_first_intact(self):
        """If the second POST fails with insufficient stock, the first POST
        must already have been committed (each is its own transaction)."""
        url = "/api/v2/surgeries/used-items/"
        # First item: valid
        self.client.post(url, {
            "surgery": self.surgery.id,
            "product": self.p1.id,
            "quantity": "30",
        })
        # Second item: exceeds stock
        resp = self.client.post(url, {
            "surgery": self.surgery.id,
            "product": self.p2.id,
            "quantity": "999",
        })
        self.assertEqual(resp.status_code, 400)

        # First product was decreased
        self.p1.refresh_from_db()
        self.assertEqual(self.p1.current_stock, Decimal("70"))

        # Second product is unchanged
        self.p2.refresh_from_db()
        self.assertEqual(self.p2.current_stock, Decimal("200"))
